// Reads the frozen method table out of the generated protocol contract, so the
// SDK's request names and the server's dispatcher come from one source.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = join(here, "../../../schema/protocol-v1.json");
const outPath = join(here, "../src/methods.ts");

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const methods = Array.isArray(schema.methods)
  ? schema.methods.map((descriptor) => descriptor.method)
  : [];
if (methods.length === 0) {
  throw new Error(`${schemaPath} has no methods table`);
}
for (const method of methods) {
  if (typeof method !== "string") {
    throw new Error(`${schemaPath} has a method without a name`);
  }
}

const body = methods.map((method) => `  ${JSON.stringify(method)},`).join("\n");
const text = `// This file was generated by scripts/gen-methods.mjs from schema/protocol-v1.json.
// Do not edit this file manually; run \`npm run gen:methods\` instead.

export const METHODS = [
${body}
] as const;

export type MethodName = (typeof METHODS)[number];
`;

writeFileSync(outPath, text);
console.log(`gen:methods wrote ${methods.length} method names to ${outPath}`);
