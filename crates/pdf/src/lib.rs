//! PDF object graph work.
//!
//! The renderer (WKWebView on macOS, WebView2 on Windows) produces the page
//! content; this crate owns everything PDF-level after that: parsing the object
//! graph, validating that every font is embedded as a subset, repairing the
//! text map of the bundled CID-keyed face, appending content streams, merging
//! embedded PDF pages as vector Form XObjects, and serialising the result.
//!
//! The repair exists because a CID-keyed CFF font is encoded with its original
//! CIDs, while the macOS PDF writer builds `/ToUnicode` from subset glyph ids.
//! Rendering is correct; copying text out of the PDF is not. The CID-to-Unicode
//! table generated next to the bundled subset restores text extraction without
//! touching the drawn glyphs.

#[cfg(feature = "parse-count")]
static PARSE_COUNT: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);

/// Number of page-count parses in this process (`parse-count` feature only).
#[cfg(feature = "parse-count")]
pub fn parse_count() -> usize {
    PARSE_COUNT.load(std::sync::atomic::Ordering::SeqCst)
}

/// Reset [`parse_count`] to zero (`parse-count` feature only).
#[cfg(feature = "parse-count")]
pub fn reset_parse_count() {
    PARSE_COUNT.store(0, std::sync::atomic::Ordering::SeqCst);
}

