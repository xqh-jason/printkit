/// The `%PDF-` header every PDF must start with.
pub const PDF_MAGIC: &[u8] = b"%PDF-";

/// Characters used by the bundled Source Han Sans subset, keyed by the CID the
/// PDF text operators carry. Generated by `scripts/subset-fonts.sh`.
const SOURCE_HAN_CIDS: &str =
    include_str!("../../../assets/fonts/SourceHanSansSC-Regular-subset.cids.txt");
/// PostScript name of the bundled subset, renamed away from the OFL Reserved
/// Font Name by `scripts/subset-fonts.sh`.
const SOURCE_HAN_BASE_FONT: &str = "printkitHanSansSC-Regular";
/// BaseFont of PDFs produced before the OFL rename. `repair_text_map` still
/// accepts it so pages embedded from older printkit PDFs keep a correct map.
const LEGACY_SOURCE_HAN_BASE_FONT: &str = "SourceHanSansSC-Regular";

static SOURCE_HAN_CID_MAP: LazyLock<Vec<(u16, u32)>> = LazyLock::new(|| {
    SOURCE_HAN_CIDS
        .lines()
        .filter_map(|line| {
            let mut fields = line.split_whitespace();
            let cid = fields.next()?;
            let codepoint = fields.next()?;
            let cid = u16::from_str_radix(cid, 16).ok()?;
            let codepoint = u32::from_str_radix(codepoint, 16).ok()?;
            Some((cid, codepoint))
        })
        .collect()
});

/// Why one PDF-level step failed.
///
/// Each variant names the step that failed: parsing the renderer's output,
/// validating fonts, repairing the text map, merging embedded pages, or
/// serialising the result.
#[derive(Debug, thiserror::Error)]
pub enum PdfError {
    /// The renderer returned zero bytes.
    #[error("renderer output is empty")]
    Empty,
    /// The bytes do not start with [`PDF_MAGIC`] (`%PDF-`).
    #[error("renderer output lacks the %PDF- header")]
    NotPdf,
    /// The object graph could not be parsed, or an object referenced by a
    /// document structure is not the expected kind (the message is the
    /// parser's).
    #[error("cannot parse the PDF: {0}")]
    Parse(String),
    /// A font has no `/FontDescriptor`, or the descriptor carries no
    /// `FontFile`/`FontFile2`/`FontFile3`, so the glyphs are not in the file.
    #[error("font {font} is not embedded")]
    FontNotEmbedded {
        /// BaseFont name as written in the font dictionary, prefix included.
        font: String,
    },
    /// Renderer output carries a font without the six-letter `ABCDEF+` subset
    /// prefix. User-supplied embedded PDFs are exempt from this check: a fully
    /// embedded font is still self-contained.
    #[error("font {font} is embedded without a subset prefix")]
    FontNotSubset {
        /// BaseFont name as written in the font dictionary, prefix included.
        font: String,
    },
    /// A font dictionary has no readable `/BaseFont` name, or a Type0 font
    /// has an empty `/DescendantFonts` array.
    #[error("font dictionary has no readable BaseFont")]
    MissingBaseFont,
    /// A page number passed to [`PdfDocument::append_content`] or to the
    /// merge is outside the target document.
    #[error("page {page} does not exist")]
    MissingPage {
        /// One-based page number that was requested.
        page: u32,
    },
    /// An [`EmbeddedPage`] names a page beyond the end of its own file.
    #[error("embedded PDF has no page {page} (it has {pages})")]
    EmbeddedPageOutOfRange {
        /// One-based page requested inside the embedded PDF.
        page: u32,
        /// Page count of the embedded PDF.
        pages: u32,
    },
    /// An input PDF is encrypted: its trailer carries `/Encrypt`, or opening it
    /// reported a decryption or password error. Its strings and streams cannot
    /// be read.
    #[error("the embedded PDF is encrypted")]
    Encrypted,
    /// The merge refused one object of an embedded page: a reference that does
    /// not resolve, a page without a usable `/MediaBox` (missing, not four
    /// numbers, an empty visible area, or a `/CropBox` that does not intersect
    /// it), a `/Rotate` that is not a multiple of 90 degrees, a cycle in the
    /// page tree, or a content stream that cannot be decoded.
    #[error("object {object:?} is not supported: {reason}")]
    UnsupportedObject {
        /// Object id inside the embedded PDF.
        object: ObjectId,
        /// Why the object could not be copied.
        reason: String,
    },
    /// The object graph reachable from an embedded page is deeper than the
    /// copier follows, so it is refused instead of exhausting the stack.
    #[error("embedded PDF object graph is deeper than {limit}")]
    TooDeep {
        /// Maximum nesting depth the copier follows.
        limit: usize,
    },
    /// A placement frame has a non-finite coordinate, or a width or height
    /// that is not positive.
    #[error("embedded page frame has a non-finite or non-positive size")]
    InvalidFrame,
    /// The document has more pages than a `u32` can number, so one-based
    /// page addressing cannot reach every page.
    #[error("the PDF has more pages than a u32 can count")]
    TooManyPages,
    /// Writing the object graph failed, or the writer produced bytes without
    /// a `%PDF-` header (the message is the writer's).
    #[error("cannot serialise the PDF: {0}")]
    Save(String),
}

/// One font found in the document.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EmbeddedFont {
    /// BaseFont without the six-letter subset prefix.
    pub name: String,
    /// `Type0`, `TrueType`, `Type1` or another subtype name.
    pub subtype: String,
}

/// A parsed PDF whose objects can be inspected and changed.
#[derive(Debug)]
pub struct PdfDocument {
    inner: Document,
}

impl PdfDocument {
    /// Parse bytes produced by the renderer.
    pub fn parse(bytes: &[u8]) -> Result<Self, PdfError> {
        if bytes.is_empty() {
            return Err(PdfError::Empty);
        }
        if !is_pdf(bytes) {
            return Err(PdfError::NotPdf);
        }
        let inner =
            Document::load_mem(bytes).map_err(|error| PdfError::Parse(error.to_string()))?;
        Ok(Self { inner })
    }

    /// Every font in the object graph, validated as embedded and subsetted.
    ///
    /// A PDF without embedded subsets is not self-contained: it only renders
    /// on a host that happens to have the same fonts. This rejects those
    /// documents instead of letting them travel to a printer.
    pub fn embedded_fonts(&self) -> Result<Vec<EmbeddedFont>, PdfError> {
        self.embedded_fonts_with_policy(true)
    }

    /// Validate every font as embedded. Renderer output must also be subsetted;
    /// a user-supplied embedded PDF may legally carry a full embedded font (it
    /// is still self-contained), so that check is optional.
    fn embedded_fonts_with_policy(
        &self,
        require_subset: bool,
    ) -> Result<Vec<EmbeddedFont>, PdfError> {
        let mut fonts = Vec::new();
        for id in font_object_ids(&self.inner) {
            let dictionary = self
                .inner
                .get_dictionary(id)
                .map_err(|error| PdfError::Parse(error.to_string()))?;
            let base_font = base_font(dictionary)?;
            let descriptor = font_descriptor(&self.inner, dictionary)?;
            if descriptor.is_none_or(|descriptor| !has_font_program(descriptor)) {
                return Err(PdfError::FontNotEmbedded {
                    font: base_font.to_owned(),
                });
            }
            let name = if require_subset {
                strip_subset_prefix(base_font).ok_or_else(|| PdfError::FontNotSubset {
                    font: base_font.to_owned(),
                })?
            } else {
                base_font
            };
            let subtype = dictionary
                .get(b"Subtype".as_slice())
                .ok()
                .and_then(name_str)
                .unwrap_or("unknown")
                .to_owned();
            fonts.push(EmbeddedFont {
                name: name.to_owned(),
                subtype,
            });
        }
        Ok(fonts)
    }

    /// Replace the text map of the bundled CID-keyed face.
    ///
    /// Returns the number of fonts whose map was replaced. Other fonts are left
    /// untouched: their writer supplies a map keyed by the codes they use.
    ///
    /// Every subset of one face carries the same code-to-character relation, so
    /// the replacement map is built and compressed once and shared by every
    /// repaired font. A page that uses the face gets its own subset object, and
    /// a per-font map would otherwise repeat the whole table once per page.
    pub fn repair_text_map(&mut self) -> Result<usize, PdfError> {
        let ids = font_object_ids(&self.inner);
        let mut targets = Vec::new();
        let mut stale = Vec::new();
        for id in ids {
            let dictionary = self
                .inner
                .get_dictionary(id)
                .map_err(|error| PdfError::Parse(error.to_string()))?;
            if dictionary
                .get(b"Subtype".as_slice())
                .ok()
                .and_then(name_str)
                != Some("Type0")
            {
                continue;
            }
            let Ok(base_font) = base_font(dictionary) else {
                continue;
            };
            let Some(name) = strip_subset_prefix(base_font) else {
                continue;
            };
            if name != SOURCE_HAN_BASE_FONT && name != LEGACY_SOURCE_HAN_BASE_FONT {
                continue;
            }
            if let Ok(old) = dictionary
                .get(b"ToUnicode".as_slice())
                .and_then(|value| value.as_reference())
            {
                stale.push(old);
            }
            targets.push(id);
        }
        if targets.is_empty() {
            return Ok(0);
        }

        let mut stream = Stream::new(cmap_dictionary(), to_unicode_cmap(&SOURCE_HAN_CID_MAP));
        stream
            .compress()
            .map_err(|error| PdfError::Save(error.to_string()))?;
        let unicode_id = self.new_object(Object::Stream(stream));
        for id in &targets {
            self.inner
                .get_dictionary_mut(*id)
                .map_err(|error| PdfError::Parse(error.to_string()))?
                .set("ToUnicode", Object::Reference(unicode_id));
        }
        for old in stale {
            self.inner.objects.remove(&old);
        }
        Ok(targets.len())
    }

    /// Append a content stream to page `page`, keeping the existing streams.
    ///
    /// Page numbers are one-based and follow document order.
    pub fn append_content(&mut self, page: u32, content: &[u8]) -> Result<(), PdfError> {
        let pages: BTreeMap<u32, ObjectId> = self.inner.get_pages();
        let page_id = pages
            .get(&page)
            .copied()
            .ok_or(PdfError::MissingPage { page })?;
        self.inner
            .add_page_contents(page_id, content.to_vec())
            .map_err(|error| PdfError::Parse(error.to_string()))
    }

    /// Remove writer metadata that changes between identical renders.
    ///
    /// The platform PDF writer stamps `CreationDate`, `ModDate` and a random
    /// trailer `/ID` on every export. Those bytes make two renders of the same
    /// document differ even when the visible page is identical, which breaks
    /// replay checks. Neither the dates nor an ID carry information a printer
    /// needs, so dropping them is safe.
    fn strip_volatile_metadata(&mut self) {
        self.inner.trailer.remove(b"ID");
        let info = self.inner.trailer.get(b"Info").ok().cloned();
        match info {
            Some(Object::Reference(id)) => {
                if let Ok(info) = self.inner.get_dictionary_mut(id) {
                    strip_info_dates(info);
                }
            }
            Some(Object::Dictionary(mut info)) => {
                strip_info_dates(&mut info);
                self.inner.trailer.set("Info", info);
            }
            _ => {}
        }
    }

    /// Set the metadata written to the trailer's `/Info` dictionary.
    ///
    /// `Title` and `Subject` both become `title`; `Creator` is always
    /// `printkit`. Values are stored as UTF-16BE hex strings, so non-ASCII
    /// titles stay valid. Other `/Info` entries (such as `Producer`) are kept.
    pub fn set_metadata(&mut self, title: &str) {
        set_info(&mut self.inner, title);
    }

    /// Serialise the object graph back to bytes.
    ///
    /// Volatile writer metadata is stripped first, so the same object graph
    /// always serialises to the same bytes.
    pub fn into_bytes(mut self) -> Result<Bytes, PdfError> {
        self.strip_volatile_metadata();
        let mut buffer = Vec::new();
        self.inner
            .save_to(&mut buffer)
            .map_err(|error| PdfError::Save(error.to_string()))?;
        if !is_pdf(&buffer) {
            return Err(PdfError::NotPdf);
        }
        Ok(Bytes::from(buffer))
    }

    fn new_object(&mut self, object: Object) -> ObjectId {
        self.inner.max_id += 1;
        let id = (self.inner.max_id, 0);
        self.inner.objects.insert(id, object);
        id
    }
}

/// Build a blank PDF with one page per supplied millimetre size.
///
/// The all-`pdf`-item path uses this as the target document, so the renderer's
/// WebView is not invoked just to produce empty pages that will be overlaid.
pub fn blank_pages(sizes: &[(f64, f64)]) -> Result<Bytes, PdfError> {
    let mut document = Document::with_version("1.5");
    let pages_id = document.add_object(Dictionary::new());
    let contents_id = document.add_object(Stream::new(Dictionary::new(), Vec::new()));
    let mut kids = Vec::new();
    for (width, height) in sizes {
        let mut page = Dictionary::new();
        page.set("Type", "Page");
        page.set("Parent", Object::Reference(pages_id));
        page.set(
            "MediaBox",
            vec![
                0.into(),
                0.into(),
                Object::Real(*width as f32),
                Object::Real(*height as f32),
            ],
        );
        page.set("Contents", Object::Reference(contents_id));
        page.set("Resources", Dictionary::new());
        kids.push(Object::Reference(document.add_object(page)));
    }
    let mut pages = Dictionary::new();
    pages.set("Type", "Pages");
    pages.set("Kids", kids);
    pages.set("Count", i64::try_from(sizes.len()).unwrap_or(i64::MAX));
    document.objects.insert(pages_id, Object::Dictionary(pages));
    let mut catalog = Dictionary::new();
    catalog.set("Type", "Catalog");
    catalog.set("Pages", Object::Reference(pages_id));
    let catalog_id = document.add_object(catalog);
    document.trailer.set("Root", Object::Reference(catalog_id));
    let mut buffer = Vec::new();
    document
        .save_to(&mut buffer)
        .map_err(|error| PdfError::Save(error.to_string()))?;
    if !is_pdf(&buffer) {
        return Err(PdfError::NotPdf);
    }
    Ok(Bytes::from(buffer))
}

/// Validate renderer output, merge embedded pages, and return one PDF.
///
/// The renderer already embeds the web fonts; this step proves that it did,
/// repairs the text map of the bundled CID-keyed face, paints every embedded
/// page as a vector Form XObject, and re-serialises. With no embedded pages it
/// is exactly [`assemble`].
pub fn assemble_embedded(pdf: Bytes, pages: &[EmbeddedPage]) -> Result<Bytes, PdfError> {
    assemble_embedded_with_title(pdf, pages, None)
}

/// Merge embedded pages and set the PDF title/creator/subject when given.
pub fn assemble_embedded_with_title(
    pdf: Bytes,
    pages: &[EmbeddedPage],
    title: Option<&str>,
) -> Result<Bytes, PdfError> {
    let mut document = PdfDocument::parse(&pdf)?;
    // The renderer's own output must always be subsetted; check it before
    // merging user-supplied pages so their full embedded fonts are not
    // mistaken for renderer output.
    document.embedded_fonts()?;
    document.repair_text_map()?;
    merge::merge(&mut document.inner, pages)?;
    if !pages.is_empty() {
        // User-supplied PDF pages may embed a complete font; requiring the
        // six-letter subset prefix would reject a self-contained document.
        document.embedded_fonts_with_policy(false)?;
    }
    if let Some(title) = title {
        document.set_metadata(title);
    }
    document.into_bytes()
}

/// Validate renderer output and return a self-contained PDF.
pub fn assemble(pdf: Bytes) -> Result<Bytes, PdfError> {
    assemble_embedded(pdf, &[])
}

/// Whether the bytes start with a PDF header.
pub fn is_pdf(bytes: &[u8]) -> bool {
    bytes.starts_with(PDF_MAGIC)
}
/// Set the document title/creator/subject in the trailer `/Info`.
pub(crate) fn set_info(document: &mut Document, title: &str) {
    let info_id = match document.trailer.get(b"Info".as_slice()) {
        Ok(Object::Reference(id)) => Some(*id),
        Ok(Object::Dictionary(dictionary)) => {
            let mut copy = dictionary.clone();
            set_info_dictionary(&mut copy, title);
            document.trailer.set("Info", Object::Dictionary(copy));
            return;
        }
        _ => None,
    };
    let id = match info_id {
        Some(id) => id,
        None => {
            document.max_id = document.max_id.saturating_add(1);
            let id = (document.max_id, 0);
            document
                .objects
                .insert(id, Object::Dictionary(Dictionary::new()));
            document.trailer.set("Info", Object::Reference(id));
            id
        }
    };
    if let Ok(dictionary) = document.get_dictionary_mut(id) {
        set_info_dictionary(dictionary, title);
    }
}

fn set_info_dictionary(dictionary: &mut Dictionary, title: &str) {
    dictionary.set("Title", pdf_text(title));
    dictionary.set("Subject", pdf_text(title));
    dictionary.set("Creator", pdf_text("printkit"));
}

/// PDF text string as UTF-16BE hex, so non-ASCII titles stay valid.
fn pdf_text(value: &str) -> Object {
    let mut bytes = vec![0xFE, 0xFF];
    for unit in value.encode_utf16() {
        bytes.extend_from_slice(&unit.to_be_bytes());
    }
    Object::String(bytes, lopdf::StringFormat::Hexadecimal)
}

/// Delete the two date entries every writer stamps into the document info.
fn strip_info_dates(info: &mut Dictionary) {
    info.remove(b"CreationDate");
    info.remove(b"ModDate");
}

fn font_object_ids(document: &Document) -> Vec<ObjectId> {
    document
        .objects
        .iter()
        .filter_map(|(id, object)| match object {
            Object::Dictionary(dictionary)
                if dictionary.get(b"Type".as_slice()).ok().and_then(name_str) == Some("Font") =>
            {
                Some(*id)
            }
            _ => None,
        })
        .collect()
}

fn base_font(dictionary: &Dictionary) -> Result<&str, PdfError> {
    dictionary
        .get(b"BaseFont".as_slice())
        .ok()
        .and_then(name_str)
        .ok_or(PdfError::MissingBaseFont)
}

/// A PDF name as UTF-8. Names this crate compares against are ASCII, so a name
/// that is not valid UTF-8 cannot match any of them.
fn name_str(object: &Object) -> Option<&str> {
    std::str::from_utf8(object.as_name().ok()?).ok()
}

/// A six-letter uppercase prefix plus `+`, as written for embedded subsets.
fn strip_subset_prefix(base_font: &str) -> Option<&str> {
    let (prefix, name) = base_font.split_once('+')?;
    if prefix.len() != 6 || !prefix.bytes().all(|byte| byte.is_ascii_uppercase()) {
        return None;
    }
    Some(name)
}

fn font_descriptor<'a>(
    document: &'a Document,
    font: &'a Dictionary,
) -> Result<Option<&'a Dictionary>, PdfError> {
    let target = if font.get(b"Subtype".as_slice()).ok().and_then(name_str) == Some("Type0") {
        let descendants = font
            .get(b"DescendantFonts".as_slice())
            .map_err(|error| PdfError::Parse(error.to_string()))?;
        let first = descendants
            .as_array()
            .map_err(|error| PdfError::Parse(error.to_string()))?
            .first()
            .ok_or(PdfError::MissingBaseFont)?;
        let first = match first {
            Object::Reference(id) => document
                .get_object(*id)
                .map_err(|error| PdfError::Parse(error.to_string()))?,
            object => object,
        };
        first
            .as_dict()
            .map_err(|error| PdfError::Parse(error.to_string()))?
    } else {
        font
    };
    match target.get(b"FontDescriptor".as_slice()) {
        Ok(Object::Reference(id)) => document
            .get_dictionary(*id)
            .map(Some)
            .map_err(|error| PdfError::Parse(error.to_string())),
        Ok(Object::Dictionary(dictionary)) => Ok(Some(dictionary)),
        Ok(_) | Err(_) => Ok(None),
    }
}

fn has_font_program(descriptor: &Dictionary) -> bool {
    ["FontFile", "FontFile2", "FontFile3"]
        .iter()
        .any(|key| descriptor.get(key.as_bytes()).is_ok())
}

fn cmap_dictionary() -> Dictionary {
    let mut system = Dictionary::new();
    system.set(
        "Registry",
        Object::String(b"Adobe".to_vec(), lopdf::StringFormat::Literal),
    );
    system.set(
        "Ordering",
        Object::String(b"UCS".to_vec(), lopdf::StringFormat::Literal),
    );
    system.set("Supplement", Object::Integer(0));

    let mut dictionary = Dictionary::new();
    dictionary.set("Type", "CMap");
    dictionary.set("CMapName", "Adobe-Identity-UCS");
    dictionary.set("CIDSystemInfo", Object::Dictionary(system));
    dictionary
}

fn to_unicode_cmap(cid_map: &[(u16, u32)]) -> Vec<u8> {
    let mut out = String::with_capacity(256 + cid_map.len() * 20);
    out.push_str(
        "/CIDInit /ProcSet findresource begin\n\
         12 dict begin\n\
         begincmap\n\
         /CIDSystemInfo << /Registry (Adobe) /Ordering (UCS) /Supplement 0 >> def\n\
         /CMapName /Adobe-Identity-UCS def\n\
         /CMapType 2 def\n\
         1 begincodespacerange\n<0000><FFFF>\nendcodespacerange\n",
    );
    for chunk in cid_map.chunks(100) {
        let _ = writeln!(out, "{} beginbfchar", chunk.len());
        for (cid, codepoint) in chunk {
            match utf16_hex(*codepoint) {
                Some(unicode) => {
                    let _ = writeln!(out, "<{cid:04x}><{unicode}>");
                }
                None => continue,
            }
        }
        out.push_str("endbfchar\n");
    }
    out.push_str("endcmap\nCMapName currentdict /CMap defineresource pop\nend\nend\n");
    out.into_bytes()
}

/// UTF-16BE hex digits for a code point; `None` outside the Unicode range.
fn utf16_hex(codepoint: u32) -> Option<String> {
    if codepoint <= 0xFFFF {
        return Some(format!("{codepoint:04x}"));
    }
    if codepoint > 0x10_FFFF {
        return None;
    }
    let offset = codepoint - 0x1_0000;
    let high = 0xD800 + (offset >> 10);
    let low = 0xDC00 + (offset & 0x3FF);
    Some(format!("{high:04x}{low:04x}"))
}

