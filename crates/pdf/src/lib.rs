    #[test]
    fn metadata_title_is_utf16be_and_survives_serialisation() {
        let mut document = PdfDocument::parse(&sample_pdf("AAAAAB+Fake")).unwrap();
        document.set_metadata("Café Invoice");
        let bytes = document.into_bytes().unwrap();
        let reparsed = PdfDocument::parse(&bytes).unwrap();
        let info_id = reparsed
            .inner
            .trailer
            .get(b"Info".as_slice())
            .unwrap()
            .as_reference()
            .unwrap();
        let info = reparsed.inner.get_dictionary(info_id).unwrap();
        let title = info.get(b"Title".as_slice()).unwrap().as_str().unwrap();
        assert_eq!(&title[..2], &[0xFE, 0xFF]);
        let decoded: String = title[2..]
            .as_chunks::<2>()
            .0
            .iter()
            .map(|pair| u16::from_be_bytes(*pair))
            .map(|unit| char::from_u32(u32::from(unit)).unwrap_or('?'))
            .collect();
        assert_eq!(decoded, "Café Invoice");
        assert_eq!(
            info.get(b"Creator".as_slice())
                .unwrap()
                .as_str()
                .unwrap()
                .len(),
            2 + 8 * 2
        );
    }

